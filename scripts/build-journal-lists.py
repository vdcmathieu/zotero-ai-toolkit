#!/usr/bin/env python3
"""Regenerate src/journal-lists.js from the ABDC Journal Quality List CSV.

Usage:
    python3 scripts/build-journal-lists.py path/to/abdc-jql.csv

The CSV is the "2022 JQL" sheet of the official ABDC workbook exported with
columns: Journal Title, 2022 rating, Publisher, ISSN, ISSN Online, ...
(the aaronw22/journal-quality GitHub mirror ships exactly that file).

The FT50 list is hard-coded below (Financial Times, 2016 revision, still
current in 2026); its ISSNs are looked up in the ABDC CSV, which contains all
fifty journals.
"""
