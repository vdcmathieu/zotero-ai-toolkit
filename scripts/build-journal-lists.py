# Extra names the same journal is commonly filed under in Zotero.
FT50_ALIASES = {
    "MIT Sloan Management Review": ["Sloan Management Review"],
    "Manufacturing and Service Operations Management": ["M&SOM"],
    "MIS Quarterly": ["Management Information Systems Quarterly"],
}


def norm(name):
    """Same normalisation as ZoteroJournalRank.normName in src/journal-rank.js."""
    s = name.lower().replace("&", " and ")
    s = re.sub(r"\s*\([^)]*\)\s*$", "", s)  # trailing "(US)", "(UK)" qualifiers
    s = re.sub(r"^the\s+", "", s)
    s = re.sub(r"[^a-z0-9]+", " ", s).strip()
    s = re.sub(r"\s+", " ", s)
    return s


def issns(row):
    out = []
    for key in ("ISSN", "ISSN Online"):
        v = (row.get(key) or "").strip().upper()
        if re.fullmatch(r"\d{4}-\d{3}[\dX]", v) and v not in out:
            out.append(v)
    return out


def main(csv_path):
    rows = list(csv.DictReader(open(csv_path, encoding="utf-8-sig")))
    by_norm = {norm(r["Journal Title"]): r for r in rows}

    ft50 = []
    for name in FT50:
        row = by_norm.get(norm(name))
        if row is None:
            sys.exit(f"FT50 journal not found in ABDC CSV: {name}")
        ft50.append({
            "name": name,
            "aliases": FT50_ALIASES.get(name, []),
            "issn": issns(row),
        })

    abdc = []
    for r in rows:
        rating = (r.get("2022 rating") or "").strip()
        if rating not in ("A*", "A"):
            continue
        abdc.append({
            "name": r["Journal Title"].strip(),
            "rating": rating,
            "issn": issns(r),
        })
    abdc.sort(key=lambda j: j["name"].lower())

    def js_array(items):
        return "[\n" + ",\n".join("\t\t" + json.dumps(i, ensure_ascii=False) for i in items) + ",\n\t]"

    out = Path(__file__).resolve().parent.parent / "src" / "journal-lists.js"
    out.write_text(
        "/* eslint-disable */\n"
        "// GENERATED by scripts/build-journal-lists.py - do not edit by hand.\n"
        "//\n"
        "// Journal lists used by the Journal rank column (src/journal-rank.js):\n"
        "//  - FT50: the Financial Times 50 journals (2016 revision), with ISSNs.\n"
        f"//  - ABDC_A: the {len(abdc)} journals rated A* or A in the ABDC Journal Quality List 2022.\n"
        "\n"
        "var ZoteroJournalLists = {\n"
        f"\tFT50: {js_array(ft50)},\n"
        f"\tABDC_A: {js_array(abdc)},\n"
        "};\n",
        encoding="utf-8",
    )
    print(f"Wrote {out}: {len(ft50)} FT50, {len(abdc)} ABDC A*/A journals")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
